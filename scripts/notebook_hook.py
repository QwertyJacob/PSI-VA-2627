"""
MkDocs hook: an «Apri in Colab» button next to every runnable script.

On each week page (docs/settimana_NN/index.md) that has a notebook in
notebooks/settimana_NN.ipynb, every `<div class="psi-exec"` gets a `data-colab`
attribute with the Colab URL of that notebook, scrolled to the same script;
docs/javascripts/pyodide/code-runner.js turns the attribute into the button.
Pages without a notebook get no button, so a new week never shows a dead link.

The notebooks are generated by scripts/build_notebooks.py. When a page's scripts
no longer match its notebook, the build logs a warning, which makes
`mkdocs build --strict` (the deploy workflow) fail: an out-of-date notebook
never goes online unnoticed.
"""
import logging
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_notebooks import (  # noqa: E402
    WEEK_PAGE_RE,
    colab_url,
    extract_scripts,
    notebook_code_cells,
    notebook_path,
)

log = logging.getLogger("mkdocs.plugins.notebook_hook")

_DIV_RE = re.compile(r'<div\s+class="psi-exec"')


def on_page_markdown(markdown, page, config, files):
    m = WEEK_PAGE_RE.fullmatch(page.file.src_uri)
    if not m:
        return markdown
    week = m.group(1)
    scripts = extract_scripts(markdown)
    path = notebook_path(week)
    if not scripts or not path.exists():
        return markdown

    if [s.code for s in scripts] != notebook_code_cells(path):
        log.warning(
            "notebooks/%s non corrisponde agli script di %s: "
            "esegui python scripts/build_notebooks.py",
            path.name, page.file.src_uri,
        )

    lines = markdown.split("\n")
    for k, script in enumerate(scripts, start=1):
        url = colab_url(config["repo_url"], week, k)
        lines[script.div_line] = _DIV_RE.sub(
            lambda _: f'<div class="psi-exec" data-colab="{url}"',
            lines[script.div_line], count=1,
        )
    return "\n".join(lines)
